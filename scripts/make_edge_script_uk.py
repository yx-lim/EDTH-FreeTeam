STEP_S = 60
GAPS: dict[int, str] = {}


def write() -> None:
    DOCS.mkdir(exist_ok=True)
    lines, section = ["# Ukrainian edge-case script (Irpin zone)", "",
                      "100 radio reports in Ukrainian, Russian and surzhyk, one a minute, set in Irpin (pick **Ірпінь** "
                      "in the zone dropdown). Each line says what should happen. Callsigns and codenames are invented "
                      "(`data/callsigns.json`, `data/zones/irpin/codenames.json`).", ""], None
    for i, (sec, text, expect) in enumerate(SCRIPT, 1):
        if sec != section:
            lines += ["", f"## {sec}", ""]
            section = sec
        gap = f"  \n   ⚠ offline rules today: {GAPS[i]}" if i in GAPS else ""
        lines.append(f"{i}. «{text}»  \n   → {expect}{gap}")
    lines += ["", "## Checked offline", "",
              (f"{len(GAPS)} of {len(SCRIPT)} lines are marked ⚠: the offline rules get them wrong today. " if GAPS else
               "Every line behaves as written with the offline rules (no cloud model). ") +
              "Checked by playing the script through the radio-net layer: `python -m scripts.make_edge_script_uk --play`."]
    (DOCS / "edge_case_script_uk.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (DOCS / "edge_case_script_uk.jsonl").write_text(
        "".join(json.dumps({"t": i * STEP_S, "text": t}, ensure_ascii=False) + "\n" for i, (_, t, _) in enumerate(SCRIPT)),
        encoding="utf-8")
    print(f"{len(SCRIPT)} reports -> docs/edge_case_script_uk.md and .jsonl")


async def play() -> None:
    os.environ["ZONE"] = "irpin"
    os.environ.setdefault("EXTRACTOR", "rules")
    from backend.geo import Gazetteer
    from backend.net import Net
    from backend.tracker import Tracker
    from backend.zone import DIR
    gaz = Gazetteer(DIR / "gazetteer.json", aliases=DIR / "aliases.json", custom=DIR / "no_custom_places.json",
                    codenames=DIR / "codenames.json")
    net = Net(Tracker(gaz))
    for i, (sec, text, expect) in enumerate(SCRIPT, 1):
        out = await net.hear(text, now=1_000_000 + i * STEP_S)
        tx = out["transmissions"][0] if out["transmissions"] else {}
        ev = "; ".join(f"{e['callsign']}:{'OK' if e['ok'] else 'NO'} {e.get('anchor') or ''} {e.get('note') or ''}".strip()
                       for e in out["events"]) or "-"
        print(f"{i:3} {tx.get('kind') or '-':11} {ev[:120]}")


if __name__ == "__main__":
    write()
    if "--play" in sys.argv:
        asyncio.run(play())
